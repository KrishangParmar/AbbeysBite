package com.abbeysbite.app.core.config

/**
 * Canonical legal/policy content, bundled in-app so the screens are always
 * genuine and functional. The same source text lives in `legal/` at the repo
 * root as HTML for hosting; once hosted, the `*_URL` config values point
 * there and the app offers "open in browser" alongside the in-app text.
 */
object LegalContent {

    enum class Kind(val title: String) {
        PRIVACY("Privacy Policy"),
        TERMS("Terms of Service"),
        GUIDELINES("Community Guidelines"),
    }

    fun body(kind: Kind): String = when (kind) {
        Kind.PRIVACY -> PRIVACY
        Kind.TERMS -> TERMS
        Kind.GUIDELINES -> GUIDELINES
    }

    fun hostedUrl(kind: Kind): String? = when (kind) {
        Kind.PRIVACY -> AppSecrets.privacyPolicyUrl
        Kind.TERMS -> AppSecrets.termsUrl
        Kind.GUIDELINES -> AppSecrets.communityGuidelinesUrl
    }.takeIf { it.isNotBlank() && it != "PENDING" }

    val supportUrl: String? =
        AppSecrets.supportUrl.takeIf { it.isNotBlank() && it != "PENDING" }

    private val PRIVACY = """
Abbey's Bite Privacy Policy

Last updated: September 2026

Abbey's Bite helps you make meals you already love more satisfying. Privacy is a design principle, not an afterthought.

WHAT STAYS ON YOUR PHONE
• Meal photos you analyze are processed by an AI model that runs entirely on your device. Analysis photos and your assistant conversations are not sent to our servers or to any AI provider.
• Photos you choose to save to your Journal are stored privately in your account and are visible only to you.

WHAT WE STORE IN YOUR ACCOUNT
• Account basics: email address, username, display name, optional avatar and bio.
• Your preferences: dietary preference, foods you avoid, cooking setup, pantry items.
• Journal entries you save: meal name, date, your notes, and the nutrition summary produced on your device.
• Community content you publish: recipes, likes, saves, reports.
• Friend relationships and the specific progress stats you explicitly choose to share.
• Subscription state (managed by RevenueCat using your account id — we never see your payment details).

WHAT FRIENDS CAN SEE
Nothing, until you opt in. Progress sharing is off by default, per-stat, and never includes meal photos, conversations, notes, or foods you avoid.

ANALYTICS
We record coarse product events (for example "meal scan completed") with no meal content, no photos, and no conversation text.

NOTIFICATIONS
If you enable them, we use OneSignal to deliver pushes for the categories you turn on. Your account id is used so notifications reach the right person.

ADVERTISING
Free accounts see a small number of sponsored cards in the Community feed, served by Google AdMob. Premium removes ads entirely. We never use your meal data to target ads.

DELETING YOUR DATA
Delete your account any time from You → Delete account. This permanently removes your profile, journal, photos, recipes, relationships and conversations from our systems.

CONTACT
Questions about privacy: use You → Help & support.
""".trimIndent()


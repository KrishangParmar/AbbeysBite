    private val GUIDELINES = """
Abbey's Bite Community Guidelines

Hidden Gems is a warm corner of the internet for real food from real kitchens. Keep it that way:

BE GENEROUS
Share recipes you actually make. Simple is welcome — a five-minute upgrade helps more people than a showpiece.

BE KIND
No shaming anyone's food, body, budget or kitchen. We don't do "good foods" and "bad foods" here.

BE HONEST
No stolen recipes or images. Credit where credit is due. No spam, ads or self-promotion outside your own recipes.

BE SAFE
